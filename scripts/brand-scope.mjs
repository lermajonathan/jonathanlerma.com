// Generates src/styles/brand-scope.css from the installed Pance packages.
// Runs before `dev` and `build`. Logic lives in ./lib/brand-scope.mjs (unit-tested).
import fs from 'node:fs';
import { buildBrandScopeCss } from './lib/brand-scope.mjs';

const SOURCES = ['node_modules/@pance/tokens/dist/tokens.css', 'node_modules/@pance/react/dist/styles.css'];
const OUTPUT = 'src/styles/brand-scope.css';

const css = SOURCES.map((file) => fs.readFileSync(file, 'utf8')).join('\n');
fs.mkdirSync('src/styles', { recursive: true });
fs.writeFileSync(OUTPUT, `/* generated by scripts/brand-scope.mjs — do not edit */\n${buildBrandScopeCss(css)}\n`);
console.log(`brand-scope: wrote ${OUTPUT}`);
